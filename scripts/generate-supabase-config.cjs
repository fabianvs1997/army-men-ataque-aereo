// Genera `src/supabase-env.js` (gitignorado, nunca en el repo) a partir
// de variables de entorno, para que la URL y la clave ANON de Supabase
// no queden nunca hardcodeadas en el código.
//
// Uso en local:
//   cp .env.example .env   # y rellena los dos valores
//   node scripts/generate-supabase-config.cjs
//   # o directamente: SUPABASE_URL=... SUPABASE_ANON_KEY=... node scripts/generate-supabase-config.cjs
//
// Uso en producción: el workflow `.github/workflows/deploy-pages.yml`
// ejecuta este mismo script con los secretos de GitHub como variables
// de entorno (SUPABASE_URL y SUPABASE_ANON_KEY) y publica el archivo
// generado solo dentro del artefacto de GitHub Pages.
//
// Sin variables, genera un archivo vacío y el juego va como invitado.
// Con una sola de las dos, o con valores no válidos, falla (exit 1)
// para que el error se vea en local o en el workflow, no en el juego.
// La clave nunca se imprime en la salida. La clave secreta
// (service_role) se rechaza siempre: no debe existir en este flujo.
'use strict';
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const DEFAULT_OUT = path.join(ROOT, 'src', 'supabase-env.js');
const DEFAULT_ENV_FILE = path.join(ROOT, '.env');

function parseArgs(argv) {
  const args = { out: DEFAULT_OUT, envFile: DEFAULT_ENV_FILE };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--out' && argv[i + 1]) args.out = path.resolve(argv[++i]);
    else if (argv[i] === '--env-path' && argv[i + 1])
      args.envFile = path.resolve(argv[++i]);
    else if (argv[i] === '--help' || argv[i] === '-h') args.help = true;
  }
  return args;
}

function parseEnvFile(file) {
  const values = {};
  let raw;
  try {
    raw = fs.readFileSync(file, 'utf8');
  } catch (_) {
    return values;
  }
  for (const line of raw.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq < 0) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    )
      value = value.slice(1, -1);
    if (key) values[key] = value;
  }
  return values;
}

function validUrl(url) {
  return /^https:\/\/[a-z0-9-]+\.supabase\.co\/?$/.test(url);
}

function validKey(key) {
  if (typeof key !== 'string' || key.length <= 20) return false;
  if (/service_role/i.test(key)) return false;
  if (/^sb_secret_/i.test(key)) return false;
  if (/^sk-/i.test(key)) return false;
  return true;
}

function main(argv, env) {
  const args = parseArgs(argv);
  if (args.help) {
    process.stdout.write(
      'Uso: node scripts/generate-supabase-config.cjs [--out <ruta>] [--env-path <ruta>]\n' +
        'Lee SUPABASE_URL y SUPABASE_ANON_KEY de variables de entorno o de .env.\n',
    );
    return 0;
  }
  const fromFile = parseEnvFile(args.envFile);
  const url = env.SUPABASE_URL || fromFile.SUPABASE_URL || '';
  const anonKey = env.SUPABASE_ANON_KEY || fromFile.SUPABASE_ANON_KEY || '';
  let config;
  if (!url && !anonKey) {
    config = { url: '', anonKey: '' };
    process.stdout.write(
      'Supabase no configurado: se genera un archivo vacío (modo invitado).\n',
    );
  } else {
    if (!url || !anonKey) {
      process.stderr.write(
        'Error: hacen falta las dos variables, SUPABASE_URL y SUPABASE_ANON_KEY.\n',
      );
      return 1;
    }
    if (!validUrl(url)) {
      process.stderr.write(
        'Error: SUPABASE_URL debe ser https://<proyecto>.supabase.co\n',
      );
      return 1;
    }
    if (!validKey(anonKey)) {
      process.stderr.write(
        'Error: SUPABASE_ANON_KEY no es válida (¿clave secreta/service_role?). ' +
          'Solo vale la Publishable key (ANON).\n',
      );
      return 1;
    }
    config = { url, anonKey };
    process.stdout.write(
      'Configuración de Supabase generada en ' +
        path.relative(ROOT, args.out) +
        ' (la clave no se muestra).\n',
    );
  }
  const content =
    '// GENERATED by scripts/generate-supabase-config.cjs from environment\n' +
    '// variables. Do not edit by hand and do not commit this file: it is\n' +
    '// generated at deploy time (GitHub Actions secrets) or in local\n' +
    '// development from .env. See docs/SUPABASE.md.\n' +
    'globalThis.__SUPABASE_CONFIG__ = ' +
    JSON.stringify(config) +
    ';\n';
  fs.mkdirSync(path.dirname(args.out), { recursive: true });
  fs.writeFileSync(args.out, content, 'utf8');
  return 0;
}

if (require.main === module) process.exitCode = main(process.argv.slice(2), process.env);
module.exports = { main, validUrl, validKey, parseEnvFile };
